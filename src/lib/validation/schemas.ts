import { z } from "zod";
import { isValidSlug } from "@/lib/content/slug";

/** "viewer" is the read-only demo role: it can open the admin area but holds no write permission. */
export const ROLES = ["admin", "editor", "author", "viewer"] as const;
export type Role = (typeof ROLES)[number];
export const POST_STATUSES = ["draft", "published", "archived"] as const;

const slugField = z
  .string()
  .trim()
  .min(1, "Slug is required")
  .max(80)
  .refine(
    isValidSlug,
    "Slug may only contain lowercase letters, numbers and single dashes, and cannot be reserved"
  );

const optionalText = (max: number) => z.string().trim().max(max).default("");

export const loginSchema = z.object({
  email: z.string().trim().toLowerCase().email().max(254),
  password: z.string().min(1).max(256),
});

/** Media ids are generated by the server (cuid-like). "" means none. */
const mediaIdField = z
  .string()
  .max(40)
  .regex(/^([a-z0-9]{10,40})?$/, "Invalid image reference")
  .default("");

/** Only http and https addresses. A canonical or share link must never be a javascript: or data: URL. */
const webUrlField = z
  .string()
  .trim()
  .max(500)
  .refine((v) => v === "" || /^https?:\/\/[^\s]+$/i.test(v), "Use a full http or https address")
  .default("");

/** SEO fields of a post. Empty strings mean "use the automatic default". */
export const seoFields = {
  seoTitle: optionalText(70),
  seoDescription: optionalText(200),
  focusKeyword: optionalText(60),
  canonicalUrl: webUrlField,
  robots: z.enum(["index", "noindex"]).default("index"),
  follow: z.enum(["follow", "nofollow"]).default("follow"),
  ogTitle: optionalText(95),
  ogDescription: optionalText(200),
  twitterCard: z.enum(["summary", "summary_large_image"]).default("summary_large_image"),
  featuredImage: mediaIdField,
  socialImage: mediaIdField,
  featuredImageAlt: optionalText(300),
};

// "" means the theme's default template. Anything else must be a custom template id.
const templateField = z
  .string()
  .max(40)
  .regex(/^([a-z][a-z-]{1,30})?$/, "Invalid template name")
  .default("");

export const postSchema = z.object({
  id: z.string().optional(),
  title: z.string().trim().min(1, "Title is required").max(200),
  slug: slugField,
  excerpt: optionalText(500),
  body: z.string().max(200_000),
  status: z.enum(POST_STATUSES),
  publishedAt: z.string().optional(), // ISO string from datetime-local, converted by the caller
  featured: z.boolean().default(false),
  categoryIds: z.array(z.string().max(64)).max(20).default([]),
  tagIds: z.array(z.string().max(64)).max(30).default([]),
  template: templateField,
  // Project facts (type, area, schedule, price). Empty values are dropped when saved.
  fields: z.record(z.string(), z.string().max(120)).default({}),
  ...seoFields,
});
export type PostInput = z.infer<typeof postSchema>;

export const pageSchema = z.object({
  id: z.string().optional(),
  title: z.string().trim().min(1).max(200),
  slug: slugField,
  body: z.string().max(200_000),
  status: z.enum(POST_STATUSES),
  template: templateField,
  seoTitle: optionalText(70),
  seoDescription: optionalText(200),
});
export type PageInput = z.infer<typeof pageSchema>;

export const taxonomySchema = z.object({
  id: z.string().optional(),
  name: z.string().trim().min(1).max(100),
  slug: slugField,
  description: optionalText(1000),
  seoDescription: optionalText(200),
});
export type TaxonomyInput = z.infer<typeof taxonomySchema>;

export const siteSettingsSchema = z.object({
  siteTitle: z.string().trim().min(1).max(120),
  siteDescription: z.string().trim().max(300),
});

export const userSchema = z.object({
  name: z.string().trim().min(1).max(100),
  email: z.string().trim().toLowerCase().email().max(254),
  role: z.enum(ROLES),
  password: z.string().min(12, "Password must be at least 12 characters").max(256),
});

export const idSchema = z.string().min(1).max(64);
